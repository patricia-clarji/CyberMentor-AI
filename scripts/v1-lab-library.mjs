function expand(items, courseId, skills, typeOverride) {
  return items.map(
    ([title, category, organization, task, expected, hint], index) => ({
      id: `${courseId}-range-${String(index + 1).padStart(2, "0")}`,
      courseId,
      title,
      category,
      difficulty: difficultyCycle[index % difficultyCycle.length],
      environmentType: typeOverride ?? typeCycle[index % typeCycle.length],
      estimatedMinutes: 20 + (index % 5) * 10,
      organization,
      task,
      expected,
      hint,
      skills,
    }),
  );
}

